#!/usr/bin/env python3
"""Run on the build server. Generate named Rust operations from pinned official inputs."""
import argparse
import hashlib
import json
import pathlib
import re

METHODS = {"get", "post", "patch", "put", "delete", "head"}


def interface_only(value, named_map=False):
    if isinstance(value, dict):
        maps = {"properties", "schemas", "paths", "headers", "content", "responses", "encoding", "securitySchemes"}
        return {key: item if not named_map and key in {"default", "enum", "const"} else interface_only(item, key in maps)
                for key, item in value.items()
                if named_map or key not in {"description", "summary", "examples", "example", "x-code-samples", "externalDocs"}}
    if isinstance(value, list):
        return [interface_only(item) for item in value]
    return value


def snake(name):
    return re.sub(r"[^a-zA-Z0-9]+", "_", re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)).lower()


def camel(name):
    return "".join(p[:1].upper() + p[1:] for p in snake(name).split("_"))


def operations(document):
    for route, methods in document.get("paths", {}).items():
        for method, operation in methods.items():
            if method in METHODS:
                yield route, method, operation


def generate(venue, documents, selected, output):
    title = venue.title()
    enum = title + "Operation"
    client = "BackpackClient" if venue == "backpack" else "LighterNativeClient"
    catalog = {"documents": documents}
    schema_path = output / "connector/specs" / (venue + ".json")
    schema_path.parent.mkdir(parents=True, exist_ok=True)
    schema_path.write_text(json.dumps(interface_only(catalog), ensure_ascii=False, separators=(",", ":")) + "\n")
    lines = ["// Generated by scripts/generate_native_api.py from official specifications. Do not edit.",
             "use super::*;", "use crate::native_api::{NativeRequest, NativeResponse, Operation};", "use std::sync::OnceLock;",
             f"fn catalog() -> &'static Value {{ static VALUE: OnceLock<Value> = OnceLock::new(); VALUE.get_or_init(|| serde_json::from_str(include_str!(\"../../specs/{venue}.json\")).expect(\"checked official catalog\")) }}",
             "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]", f"pub enum {enum} {{"]
    seen = set()
    for route, method, operation, document_key, source, family in selected:
        name = operation["operationId"]
        variant = camel(name)
        if variant in seen:
            raise ValueError("operation name collision: " + variant)
        seen.add(variant)
        lines.append(variant + ",")
    lines += ["}", f"impl {enum} {{", "pub const ALL: &'static [Self] = &["]
    lines += ["Self::" + camel(op[2]["operationId"]) + "," for op in selected]
    lines += ["];", "pub fn metadata(self) -> Operation { match self {"]
    rows = []
    for route, method, op, key, source, family in selected:
        doc = documents[key]
        name = op["operationId"]
        signed = any(p.get("name", "").lower() == "x-signature" for p in op.get("parameters", []))
        match = re.search(r"\*\*(?:Instruction|Batch commands instruction):\*\*\s*`([^`]+)`", op.get("description", ""))
        if signed and not match:
            raise ValueError("signed endpoint lacks instruction: " + name)
        instruction = "Some(" + json.dumps(match[1]) + ")" if match else "None"
        server = doc["servers"][0]["url"].rstrip("/")
        q = json.dumps
        lines.append(f"Self::{camel(name)} => {{ let document=&catalog()[\"documents\"][{q(key)}]; Operation {{id:{q(name)},method:{q(method.upper())},path:{q(route)},instruction:{instruction},source:{q(source)},default_server:{q(server)},family:{q(family)},definition:&document[\"paths\"][{q(route)}][{q(method)}],document}} }},")
        rows.append({"venue": venue, "operation": name, "method": method.upper(), "path": route,
                     "family": family, "source": source, "instruction": match[1] if match else None})
    lines += ["}}}", f"impl {client} {{"]
    for route, method, op, key, source, family in selected:
        name = op["operationId"]
        guard_arg = ", guard: Option<SubmitGuard>" if method not in ("get", "head") else ""
        guard = "guard" if guard_arg else "None"
        lines.append(f"/// `{method.upper()} {route}`. Native request/response; see the official operation catalog.")
        lines.append(f"pub async fn native_{snake(name)}(&self, request: NativeRequest{guard_arg}) -> Result<NativeResponse, ApiError> {{ self.native_request({enum}::{camel(name)},request,{guard}).await }}")
    lines.append("}")
    rust = output / f"connector/src/{venue}/native_generated.rs"
    rust.write_text("\n".join(lines) + "\n")
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("research", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()
    root, output = args.research, args.output
    html = (root / "backpack.html").read_text()
    bp = json.JSONDecoder().raw_decode(html.split("const __redoc_state = ", 1)[1])[0]["spec"]["data"]
    bp_selected = [(p, m, op, "official", "https://docs.backpack.exchange/#operation/" + op["operationId"], "exchange") for p, m, op in operations(bp)]
    rows = generate("backpack", {"official": bp}, bp_selected, output)
    sdk = json.loads((root / "lighter-openapi.json").read_text())
    revision = json.loads((root / "lighter-python-tree.json").read_text())["sha"]
    sdk_source = f"https://github.com/elliottech/lighter-python/blob/{revision}/openapi.json"
    docs = {"sdk": sdk}
    chosen = {(p, m): (p, m, op, "sdk", sdk_source, "exchange") for p, m, op in operations(sdk)}
    sources = []
    index = (root / "lighter-index.txt").read_text()
    urls = list(dict.fromkeys(re.findall(r"https://docs.lighter.xyz/api/[^)\s]+\.md", index)))
    for url in urls:
        key = "lighter-" + url.split("/api/")[1].replace("/", "_")
        file = root / key
        for block_index, block in enumerate(re.findall(r"```json\s*(.*?)\s*```", file.read_text(), re.S)):
            try:
                document = json.loads(block)
            except json.JSONDecodeError:
                continue
            if "openapi" not in document:
                continue
            family = "explorer" if "/explorer-api/" in url else "exchange"
            document_key = f"{key}#{block_index}"
            docs[document_key] = document
            sources.append({"url": url, "sha256": hashlib.sha256(file.read_bytes()).hexdigest(), "block_index": block_index, "catalog_key": document_key})
            for path, method, op in operations(document):
                if not op.get("operationId"):
                    op["operationId"] = "explorer_" + method + "_" + snake(path.strip("/"))
                chosen[(path, method)] = path, method, op, document_key, url, family
    selected = sorted(chosen.values(), key=lambda item: (item[5], item[0], item[1]))
    rows += generate("lighter", docs, selected, output)
    manifest = {"backpack_html_sha256": hashlib.sha256((root / "backpack.html").read_bytes()).hexdigest(),
                "lighter_sdk_revision": revision, "lighter_sdk_sha256": hashlib.sha256((root / "lighter-openapi.json").read_bytes()).hexdigest(),
                "documents": sources, "operations": rows}
    (output / "connector/specs/manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    inventory = ["# 官方原生 API 覆盖目录", "", "核对日期：2026-10-31。以下是已生成命名 Rust 接口的官方公开路由；编译、协议测试及实盘状态见 [接入说明](exchange_onboarding.md)。不把未公开的交易协议、内部接口或成功受理当作已完成实盘验收。", ""]
    for venue in ["backpack", "lighter"]:
        entries = [row for row in rows if row["venue"] == venue]
        inventory += [f"## {venue.title()}（{len(entries)} 个 HTTP 操作）", "", "| 操作 | HTTP | Rust 方法 | 官方来源 |", "| --- | --- | --- | --- |"]
        inventory += [f"| `{row['operation']}` | `{row['method']} {row['path']}` | `native_{snake(row['operation'])}` | [规范]({row['source']}) |" for row in entries]
        inventory.append("")
    inventory += ["## Variational（2 个公开 HTTP 操作）", "", "| HTTP | Rust 方法 | 范围 |", "| --- | --- | --- |", "| `GET /metadata/v2/stats` | `stats` / `native_stats(StatsVersion::V2)` | 推荐 v2，原生入口保留全部字段 |", "| `GET /metadata/stats` | `native_stats(StatsVersion::LegacyV1)` | 官方仍提供的废弃 v1，不转换为 v2 |", "", "[官方 Trading API](https://docs.variational.io/technical-documentation/api#trading-api)尚未开放，不能补造交易接口。", ""]
    signer_path = output / "connector/specs/lighter-signer.json"
    if signer_path.exists():
        signer = json.loads(signer_path.read_text())
        inventory += [f"## Lighter 原生签名（{len(signer['operations'])} 类交易）", "", f"固定官方提交 `{signer['revision']}`；`NativeTransaction` 对应全部 `Sign*` 导出。", "", "| C 签名入口 | Rust 交易类型 |", "| --- | --- |"]
        inventory += [f"| `{op['name']}` | `NativeTransaction::{op['name'].removeprefix('Sign')}` |" for op in signer["operations"]]
        inventory += ["", "另提供 `LighterNativeSigner::new`、`generate_api_key`、`auth_token`、`check_client`，原生内存由内部 Free 回收。", ""]
    inventory += ["## WebSocket", "", "Backpack 的 20 个流模式见 `backpack::WEBSOCKET_STREAMS`；Lighter 的 25 个频道模式见 `lighter::WEBSOCKET_CHANNELS`。原生订阅保留完整字段、JSON/二进制消息及服务器错误，用户负责相关性和状态管理；统一运行时仍使用专门校验连续性与账户就绪的适配器。", "", "Lighter 另提供 `send_transaction` / `send_transactions`，分别使用官方 `jsonapi/sendtx` / `jsonapi/sendtxbatch` 编码。写操作不自动重发。"]
    (output / "docs/exchange_api_catalog.md").write_text("\n".join(inventory) + "\n")
    counts = {venue: sum(row["venue"] == venue for row in rows) for venue in ("backpack", "lighter")}
    print(json.dumps(counts))


if __name__ == "__main__":
    main()
