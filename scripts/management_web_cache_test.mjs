import assert from "node:assert/strict";
import fs from "node:fs";
import { createRequire } from "node:module";
const root = new URL("../", import.meta.url);
const require = createRequire(new URL("web/console/package.json", root));
const ts = require("typescript");
const code = ts.transpileModule(fs.readFileSync(new URL("web/console/src/store/resource-cache.ts", root), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
new Function("exports", code)(exports);
const { cacheResources } = exports;
const row = (kind, id, revision, body = {}) => ({ id, kind, revision: String(revision), body });
let rows = [row("parameter_preset", "parameter_preset", 1), row("dataset", "dataset", 2), row("binding", "binding", 3), row("strategy_version", "selected-old", 4)];
for (let i = 0; i < 600; i++) rows = cacheResources([row("strategy_version", "strategyVersion-" + i, i + 5)], rows, ["selected-old"]);
assert(rows.some(r => r.id === "parameter_preset"));
assert(rows.some(r => r.id === "dataset"));
assert(rows.some(r => r.id === "binding"));
assert(rows.some(r => r.id === "selected-old"));
assert.equal(rows.filter(r => r.kind === "strategy_version").length, 101);
rows = cacheResources([row("parameter_preset", "parameter_preset", 1000, { current: true })], rows);
rows = cacheResources([row("parameter_preset", "parameter_preset", 1)], rows);
assert.equal(rows.find(r => r.id === "parameter_preset").body.current, true);
for (let i = 0; i < 200; i++) rows = cacheResources([row("backtest", "result-" + i, i + 1001)], rows);
assert.equal(rows.filter(r => r.kind === "backtest").length, 100);
assert.equal(rows.filter(r => r.kind === "strategy_version").length, 100);
console.log("resource cache: catalog survives 600 updates; selected resource retained; per-kind limits and revision ordering passed");
